export function packWords(pack, difficulty = 'standard') {
  const selected = typeof pack === 'string' ? PACKS.find(item => item.id === pack) : pack;
  if (!selected) return [];
  return difficulty === 'easy' || difficulty === 'hard'
    ? selected.difficulties?.[difficulty] || selected.words
    : selected.words;
}
